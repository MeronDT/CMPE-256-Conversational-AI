"""Run the golden conversations through the agent, check tool use and number
grounding, and export sample conversations + chart images.

    python -m eval.run_eval            # all conversations
    python -m eval.run_eval required   # one conversation id
"""
from __future__ import annotations

import json
import re
import sys
from datetime import datetime
from pathlib import Path

import yaml

from econchat.agent import EconAgent, llm_config
from econchat.analytics import Econ
from econchat.data import load_all

ROOT = Path(__file__).resolve().parent.parent
FIG_DIR = ROOT / "figures"
DOCS = ROOT / "docs"
NUM = re.compile(r"(?<![\w.])[-−]?\$?\d[\d,]*\.?\d*")


def leaves(obj) -> list[float]:
    out = []
    if isinstance(obj, dict):
        for v in obj.values():
            out += leaves(v)
    elif isinstance(obj, list):
        for v in obj:
            out += leaves(v)
    elif isinstance(obj, (int, float)) and not isinstance(obj, bool):
        out.append(float(obj))
    elif isinstance(obj, str):
        out += [float(x.replace(",", "")) for x in re.findall(r"-?\d[\d,]*\.?\d*", obj) if x.replace(",", "").replace(".", "").replace("-", "").isdigit()]
    return out


def answer_numbers(text: str) -> list[str]:
    text = re.sub(r"\d+(\.\d+)?\s*[eE]\s*[-‑−]\s*\d+", " ", text)          # p-values like 6.53e-21
    text = re.sub(r"\d+(\.\d+)?\s*[×x]\s*10\^?[-‑−]?\d+", " ", text)
    text = re.sub(r"\b(19|20)\d{2}s?\s*[-–‑]\s*'?\d{2}s?\b", " ", text)    # 1982-84, 1970s-80s, 2021-22
    text = re.sub(r"\b(19|20)\d{2}(s|[-‑]\d{2})?\b", " ", text)             # years / months
    text = re.sub(r"\bQ[1-4]\b", " ", text)
    nums = []
    for m in NUM.findall(text):
        t = m.replace("$", "").replace(",", "").replace("−", "-").rstrip(".")
        if t in ("", "-"):
            continue
        nums.append(t)
    return nums


def grounded(token: str, pool: list[float], question: str) -> bool:
    try:
        a = float(token)
    except ValueError:
        return True
    if abs(a) <= 12 and a == int(a):  # small counts: "10 years", "3 quarters", "2%" target, list numbering
        return True
    if a in (100.0,) or token in question:  # 100 = index base (1982-84=100)
        return True
    dec = len(token.split(".")[1]) if "." in token else 0
    tol = 0.5 * 10 ** -dec + 1e-9
    for t in pool:
        for cand in (t, abs(t), t / 1000, t * 1000):
            if abs(cand - a) <= tol or abs(abs(cand) - abs(a)) <= tol:
                return True
    return False


def main(only: str | None = None):
    data, info = load_all()
    econ = Econ(data, info)
    spec = yaml.safe_load((ROOT / "eval" / "golden_questions.yaml").read_text())
    FIG_DIR.mkdir(exist_ok=True)
    DOCS.mkdir(exist_ok=True)
    cfg = llm_config()
    results, md = [], [
        "# Sample conversations",
        "",
        f"Generated by `python -m eval.run_eval` on {datetime.now():%Y-%m-%d %H:%M} with model `{cfg['model']}`. "
        f"Data retrieved from FRED {str(info['GDP'].get('fetched_at'))[:16].replace('T', ' ')} UTC.",
        "Each answer lists the tools it called. Charts are saved to `figures/`.",
        "",
    ]
    tokens = {"prompt_tokens": 0, "completion_tokens": 0}
    for conv in spec["conversations"]:
        if only and conv["id"] != only:
            continue
        agent = EconAgent(econ)
        conv_pool: list[float] = []  # tool results earlier in this chat are visible to the model via history
        md += [f"## {conv['title']}", ""]
        for k, turn in enumerate(conv["turns"], 1):
            q = turn["q"]
            t = agent.ask(q)
            for key in tokens:
                tokens[key] += t.usage.get(key, 0)
            called = [c["tool"] for c in t.tool_calls]
            conv_pool += [x for c in t.tool_calls for x in leaves(c["result"])]
            pool = conv_pool
            nums = answer_numbers(t.answer)
            ungrounded = [n for n in nums if not grounded(n, pool, q)]
            exp = turn.get("expect_tools", [])
            if exp:
                tools_ok = any(x in called for x in exp) or (turn.get("allow_no_tools") and not called)
            else:
                tools_ok = turn.get("allow_any_tools", False) or not any(
                    x in called for x in ("make_chart",))  # out-of-scope: no chart, data lookups are fine
            chart_ok = (not turn.get("expect_chart")) or bool(t.figures)
            chart_files = []
            for j, (fig, _) in enumerate(t.figures):
                name = f"{conv['id']}_{k:02d}_{j}.png"
                fig.write_image(FIG_DIR / name, width=1100, height=500, scale=2)
                chart_files.append(name)
            row = {"conversation": conv["id"], "turn": k, "question": q, "tools": called,
                   "tools_ok": bool(tools_ok), "chart_ok": chart_ok, "numbers_checked": len(nums),
                   "ungrounded_numbers": ungrounded, "seconds": t.seconds, "answer": t.answer}
            results.append(row)
            status = "OK " if tools_ok and chart_ok and not ungrounded else "CHK"
            print(f"[{status}] {conv['id']}#{k} {q[:60]:<60} tools={called} ungrounded={ungrounded} {t.seconds}s")
            md += [f"**User:** {q}", "", f"**Assistant:** {t.answer}", ""]
            for f in chart_files:
                md += [f"![chart](../figures/{f})", ""]
            md += [f"<sub>Tools: {', '.join(f'`{c}`' for c in called) or 'none'} · {t.seconds}s</sub>", "", "---", ""]
    n = len(results)
    summary = {
        "model": cfg["model"], "turns": n,
        "tool_selection_ok": sum(r["tools_ok"] for r in results),
        "charts_ok": sum(r["chart_ok"] for r in results),
        "fully_grounded_answers": sum(not r["ungrounded_numbers"] for r in results),
        "numbers_checked": sum(r["numbers_checked"] for r in results),
        "ungrounded_numbers": sum(len(r["ungrounded_numbers"]) for r in results),
        "tokens": tokens,
    }
    print(json.dumps(summary, indent=1))
    suffix = f"_{only}" if only else ""
    (ROOT / "eval" / f"results{suffix}.json").write_text(json.dumps({"summary": summary, "turns": results}, indent=1))
    if not only:
        (DOCS / "sample_conversations.md").write_text("\n".join(md), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
